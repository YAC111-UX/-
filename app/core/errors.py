# -*- coding: utf-8 -*-
"""
统一业务错误码与异常。【★核心模块·可复用】
约定：HTTP 状态码统一 200，用业务码 code 区分成败，message 为中文可读提示。
"""


class BizError(Exception):
    """业务异常：service 层抛出，路由层捕获后转成统一 JSON / SSE error 事件。"""

    def __init__(self, code: str, message: str):
        self.code = code
        self.message = message
        super().__init__(message)


